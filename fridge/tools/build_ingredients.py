def build():
    recipes = json.load(open(RECIPES, encoding='utf-8'))
    used = collections.Counter()
    for r in recipes:
        for i in r['ingredients']:
            used[i['name']] += 1

    items = []
    seen_names = set()

    def add(name, covers, aliases, pantry=False):
        if name in seen_names:
            raise SystemExit(f'표시명 중복: {name}')
        seen_names.add(name)
        entry = {'name': name, 'covers': covers}
        if aliases:
            entry['aliases'] = aliases
        if pantry:
            entry['pantry'] = True
        items.append(entry)

    for name, covers, aliases in GROUPED:
        add(name, covers, aliases)
    for name, covers, aliases in PANTRY:
        add(name, covers, aliases, pantry=True)

    # 사전이 레시피 재료를 전부 덮는지 검사한다.
    covered = {c for it in items for c in it['covers']}
    missing = sorted(set(used) - covered)
    if missing:
        print(f'!! 사전이 덮지 못한 레시피 재료 {len(missing)}종:', file=sys.stderr)
        for m in missing:
            print(f'   {m} ({used[m]}개 레시피)', file=sys.stderr)
        raise SystemExit(1)

    # covers 에 적었는데 레시피에 없는 이름이 있으면 오타다.
    ghost = sorted(covered - set(used))
    if ghost:
        print(f'!! 레시피에 없는 재료를 covers 에 적었다: {ghost}', file=sys.stderr)
        raise SystemExit(1)

    # 별칭이 다른 항목의 표시명과 겹치면 입력이 엉뚱한 데로 간다.
    for it in items:
        for a in it.get('aliases', []):
            if a in seen_names:
                print(f'!! 별칭 "{a}"({it["name"]}) 이 다른 항목 표시명과 겹친다',
                      file=sys.stderr)
                raise SystemExit(1)

    alias_owner = {}
    for it in items:
        for a in it.get('aliases', []):
            if a in alias_owner:
                print(f'!! 별칭 "{a}" 가 {alias_owner[a]} 와 {it["name"]} 양쪽에 있다',
                      file=sys.stderr)
                raise SystemExit(1)
            alias_owner[a] = it['name']

    ambiguous = {}
    for word, picks in AMBIGUOUS:
        if word in seen_names:
            print(f'!! "{word}" 는 이미 표시명이라 되물을 수 없다', file=sys.stderr)
            raise SystemExit(1)
        if word in alias_owner:
            print(f'!! "{word}" 가 {alias_owner[word]} 의 별칭이면서 갈림말이다',
                  file=sys.stderr)
            raise SystemExit(1)
        unknown = [p for p in picks if p not in seen_names]
        if unknown:
            print(f'!! "{word}" 의 선택지에 없는 항목: {unknown}', file=sys.stderr)
            raise SystemExit(1)
        ambiguous[word] = picks

    items.sort(key=lambda x: x['name'])
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump({'items': items, 'ambiguous': ambiguous},
                  f, ensure_ascii=False, separators=(',', ':'))

    pantry_n = sum(1 for i in items if i.get('pantry'))
    alias_n  = sum(len(i.get('aliases', [])) for i in items)
    print(f'재고 항목 {len(items)}종 (조미료 {pantry_n}종) / 별칭 {alias_n}개')
    print(f'되물을 갈림말 {len(ambiguous)}개: {", ".join(ambiguous)}')
    print(f'레시피 재료 {len(used)}종 전부 덮음')


if __name__ == '__main__':
    build()
