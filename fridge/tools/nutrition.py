def _norm(s):
    return re.sub(r'[\s_]', '', s or '')

def _load_dish_db():
    if not os.path.exists(_DB_PATH):
        return {}
    by_name = collections.defaultdict(list)
    with open(_DB_PATH, encoding='utf-8') as f:
        for row in csv.DictReader(f):
            by_name[_norm(row['식품명'])].append(row)
    best = {}
    for name, cands in by_name.items():
        cands.sort(key=lambda r: _SRC_PRIORITY.get(r['식품기원명'], 9))
        best[name] = cands[0]
    return best

DISH_DB = _load_dish_db()

def dish_db_lookup(name):
    """요리명이 DB와 정확히 일치하면 100g당 (kcal,탄수,단백,지방)을 돌려준다."""
    row = DISH_DB.get(_norm(name))
    if not row:
        return None
    try:
        return (float(row['에너지(kcal)']), float(row['탄수화물(g)']),
                float(row['단백질(g)']), float(row['지방(g)']))
    except (ValueError, TypeError):
        return None

def grams(name, amount):
    """'150g', '1큰술', '1/2대' 같은 표기를 그램으로 바꾼다."""
    a = amount.strip()

    # 괄호 안에 그램이 적혀 있으면 그 값을 최우선으로 쓴다
    # ('1모(300g)' → 300, '2장(300g)' → 300). PIECE 표 추정보다 정확하다.
    paren = re.search(r'\(\s*([\d.]+)\s*g\s*\)', a)
    if paren:
        return float(paren.group(1))

    m = re.match(r'^([\d./]+)\s*(.*)$', a)
    if not m:
        return 1.0 if '약간' in a else 0.0          # 약간 = 1g 로 본다
    num, unit = m.group(1), m.group(2).strip()
    try:
        qty = eval(num) if '/' in num else float(num)
    except Exception:
        return 0.0
    unit = re.sub(r'\(.*?\)', '', unit).strip()      # '1모(300g)' → '모'

    if unit in ('g',):   return qty
    if unit in ('ml',):  return qty
    if unit == '큰술':   return qty * TBSP.get(name, 15)
    if unit == '작은술': return qty * (TBSP.get(name, 15) / 3)
    if unit == '컵':     return qty * CUP.get(name, 200)
    w = PIECE.get((name, unit))
    if w: return qty * w
    return 0.0                                       # 모르는 단위는 0 (과대추정 방지)

OILS = ('식용유', '올리브유', '참기름')
FRY_THRESHOLD = 100      # 이보다 많은 기름은 튀김용 — 붓고 버린다
ABSORB_RATE   = 0.10     # 튀김은 재료 무게의 약 10% 를 흡수한다

def _ingredient_weights(r):
    """재료를 그램으로 환산한다.

    튀김 기름은 붓는 양이 아니라 흡수되는 양으로 바꾸고, 찜 요리의 물은
    쪄내는 데만 쓰이고 먹지 않으므로 완성 무게에서 뺀다. 둘 다 '재료로는
    들어가지만 접시에 남지 않는 것'이라 같은 이치로 처리한다."""
    weights, unknown = [], []
    for i in r['ingredients']:
        n = i['name']
        if n not in NUTRI:
            unknown.append(n); continue
        weights.append([n, grams(n, i['amount'])])

    food = sum(g for n, g in weights if n not in OILS)
    for w in weights:
        if w[0] in OILS and w[1] >= FRY_THRESHOLD:
            w[1] = min(w[1], food * ABSORB_RATE)

    if r.get('type') == '찜':
        weights = [w for w in weights if w[0] != '물']

    return weights, unknown

def compute(r):
    """레시피 1인분 영양정보를 계산한다.

    요리명이 식약처 DB와 정확히 일치하면 실측/산출값을 쓰고,
    1인분 무게는 이 레시피의 재료 총량(조리 후 기준, servings로 나눈 값)으로 잡는다.
    일치하지 않으면 재료를 하나씩 더하는 방식으로 대신한다."""
    weights, unknown = _ingredient_weights(r)
    total_g = sum(g for _, g in weights)
    s = r['servings']

    hit = dish_db_lookup(r['name'])
    if hit and total_g > 0:
        k100, c100, p100, f100 = hit
        per_serving_g = total_g / s
        ratio = per_serving_g / 100
        return (round(k100*ratio), round(c100*ratio), round(p100*ratio), round(f100*ratio)), unknown, 'db'

    kcal = carb = prot = fat = 0.0
    for n, g in weights:
        k, c, p, f = NUTRI[n]
        kcal += k*g/100; carb += c*g/100; prot += p*g/100; fat += f*g/100
    return (round(kcal/s), round(carb/s), round(prot/s), round(fat/s)), unknown, 'ingredient' 

